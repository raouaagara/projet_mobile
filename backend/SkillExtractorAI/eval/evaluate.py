"""Measures precision / recall / F1 of the skill extractor on eval/dataset.py.

Each CV is rendered to a real PDF, then read back like an uploaded CV.
Three systems are compared:
  - baseline : the old Java logic (lowercase `contains` on every catalog skill)
  - lexicon  : bilingual lexicon only (no AI model)
  - full     : lexicon + multilingual embedding model

Usage (from backend/SkillExtractorAI):
  .venv/Scripts/python -m eval.evaluate            # report + eval/RESULTS.md
  .venv/Scripts/python -m eval.evaluate --sweep    # try several semantic thresholds
  .venv/Scripts/python -m eval.evaluate --verbose  # per-CV mistakes
"""
from __future__ import annotations

import argparse
import json
from collections import defaultdict
from pathlib import Path

import pymupdf

import app.extractor as ex
from app.extractor import CatalogItem, SkillExtractor
from app.lexicon import load_lexicon
from app.pdf_text import pdf_to_text
from app.semantic import SemanticModel
from eval.dataset import CVS

HERE = Path(__file__).resolve().parent
CATALOG = [CatalogItem(c["id"], c["name"]) for c in json.loads((HERE / "catalog.json").read_text("utf-8"))]


def render_pdf(text: str) -> bytes:
    doc = pymupdf.open()
    page = doc.new_page()
    size = 10.0
    while page.insert_textbox(pymupdf.Rect(40, 40, 555, 802), text, fontsize=size, fontname="helv") < 0 and size > 6:
        doc.delete_page(0)
        page = doc.new_page()
        size -= 0.5
    data = doc.tobytes()
    doc.close()
    return data


def baseline(text: str) -> set[str]:
    low = text.lower()
    return {c.name for c in CATALOG if c.name.lower() in low}


def score(pred: set[str], gold: set[str]) -> tuple[int, int, int]:
    return len(pred & gold), len(pred - gold), len(gold - pred)


def prf(tp: int, fp: int, fn: int) -> tuple[float, float, float]:
    p = tp / (tp + fp) if tp + fp else 0.0
    r = tp / (tp + fn) if tp + fn else 0.0
    f = 2 * p * r / (p + r) if p + r else 0.0
    return p, r, f


def run(extractor: SkillExtractor, texts: dict[str, str], verbose: bool = False) -> dict:
    totals: dict[str, dict[str, list[int]]] = defaultdict(lambda: defaultdict(lambda: [0, 0, 0]))
    for cv in CVS:
        text, gold = texts[cv["id"]], set(cv["expected"])
        preds = {
            "baseline": baseline(text),
            "lexicon": {h.name for h in extractor.extract_text(text, CATALOG, semantic=False).skills},
            "full": {h.name for h in extractor.extract_text(text, CATALOG, semantic=True).skills},
        }
        for system, pred in preds.items():
            for key in (cv["lang"], "all"):
                acc = totals[system][key]
                for i, v in enumerate(score(pred, gold)):
                    acc[i] += v
        if verbose:
            full = preds["full"]
            print(f"\n{cv['id']}\n  missed: {sorted(gold - full)}\n  wrong : {sorted(full - gold)}")
    return totals


def table(totals: dict) -> str:
    rows = ["| System | Lang | Precision | Recall | F1 |", "|---|---|---|---|---|"]
    for system in ("baseline", "lexicon", "full"):
        for lang in ("en", "fr", "all"):
            p, r, f = prf(*totals[system][lang])
            rows.append(f"| {system} | {lang} | {p:.0%} | {r:.0%} | {f:.0%} |")
    return "\n".join(rows)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--sweep", action="store_true")
    parser.add_argument("--verbose", action="store_true")
    args = parser.parse_args()

    model = SemanticModel()
    if not model.load():
        print("WARNING: semantic model unavailable, 'full' = 'lexicon'")
    extractor = SkillExtractor(load_lexicon(), model)
    texts = {cv["id"]: pdf_to_text(render_pdf(cv["text"])) for cv in CVS}

    if args.sweep:
        for thr in (0.70, 0.72, 0.74, 0.76, 0.78, 0.80, 0.82, 0.85):
            ex.SEMANTIC_THRESHOLD = thr
            p, r, f = prf(*run(extractor, texts)["full"]["all"])
            print(f"threshold {thr:.2f}: precision {p:.0%}  recall {r:.0%}  F1 {f:.1%}")
        return

    totals = run(extractor, texts, args.verbose)
    report = table(totals)
    print("\n" + report)
    (HERE / "RESULTS.md").write_text(
        "# Skill extraction — evaluation\n\n"
        f"{len(CVS)} CVs ({sum(c['lang'] == 'en' for c in CVS)} EN, {sum(c['lang'] == 'fr' for c in CVS)} FR), "
        f"catalog of {len(CATALOG)} skills, semantic threshold {ex.SEMANTIC_THRESHOLD}.\n"
        "Generated by `python -m eval.evaluate`.\n\n" + report + "\n\n"
        "- **baseline** = the previous Java logic (`text.contains(skill)`).\n"
        "- **lexicon** = bilingual lexicon only; **full** = lexicon + multilingual embedding model.\n\n"
        "⚠️ The dataset is small and was also used to choose the semantic threshold, so these "
        "numbers are optimistic. Add real (anonymized) CVs to `eval/dataset.py` for a fair test.\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
